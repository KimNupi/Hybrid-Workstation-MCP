import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "src", "build-info.generated.ts");

async function collect(directory, predicate) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name, "en"))) {
    const path = resolve(directory, entry.name);
    if (entry.isDirectory() && entry.name !== "bin" && entry.name !== "obj") {
      files.push(...await collect(path, predicate));
    }
    else if (entry.isFile() && predicate(path)) files.push(path);
  }
  return files;
}

async function digestFiles(paths) {
  const hash = createHash("sha256");
  for (const path of [...paths].sort((left, right) => left.localeCompare(right, "en"))) {
    hash.update(relative(root, path).replaceAll("\\", "/"));
    hash.update("\0");
    hash.update(await readFile(path));
    hash.update("\0");
  }
  return hash.digest("hex");
}

const sourceFiles = await collect(resolve(root, "src"), (path) => (
  path.endsWith(".ts") && path !== outputPath
));
const nativeFiles = await collect(resolve(root, "native"), (path) => (
  path.endsWith(".cs") || path.endsWith(".csproj")
));
const buildRevision = await digestFiles([
  resolve(root, "package.json"),
  resolve(root, "package-lock.json"),
  resolve(root, "tsconfig.json"),
  ...sourceFiles,
  ...nativeFiles,
]);
const toolSchemaRevision = await digestFiles([resolve(root, "src", "server.ts")]);
const output = `// Generated by scripts/generate-build-info.mjs. Do not edit manually.\nexport const BUILD_INFO = Object.freeze({\n  buildRevision: "${buildRevision}",\n  toolSchemaRevision: "${toolSchemaRevision}",\n});\n`;
await writeFile(outputPath, output, "utf8");
console.log(`Generated ${outputPath}: build ${buildRevision}, tools ${toolSchemaRevision}`);
